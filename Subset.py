# Create the areas list with alternating room names and their sizes in square meters
areas = ["hallway", 11.25, 
         "kitchen", 18.0, 
         "living room", 20.0, 
         "bedroom", 10.75, 
         "bathroom", 9.50]

# Print out the second element from the list, which is the size of the hallway (index 1)
print(areas[1])

# Print out the last element in the list, which is the size of the bathroom
print(areas[-1])

# Print out the area of the living room, which is at index 5 in the list
print(areas[5])
